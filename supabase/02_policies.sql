begin;
create function public.is_admin() returns boolean language sql stable security definer set search_path=public,pg_temp as $$ select exists(select 1 from public.admins where user_id=(select auth.uid())); $$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon,authenticated;
alter table public.admins enable row level security;
alter table public.media enable row level security;
alter table public.posts enable row level security;
alter table public.weekly_picks enable row level security;
revoke all on public.admins from anon,authenticated;
grant select on public.admins to authenticated;
grant select on public.media,public.posts,public.weekly_picks to anon,authenticated;
grant insert,update,delete on public.media,public.posts,public.weekly_picks to authenticated;
create policy admins_read on public.admins for select to authenticated using(public.is_admin());
create policy media_read on public.media for select to anon,authenticated using(true);
create policy posts_read on public.posts for select to anon,authenticated using(status='published' and published_at<=now());
create policy picks_read on public.weekly_picks for select to anon,authenticated using(status='published' and published_at<=now());
create policy posts_admin_read on public.posts for select to authenticated using(public.is_admin());
create policy picks_admin_read on public.weekly_picks for select to authenticated using(public.is_admin());
create policy posts_insert on public.posts for insert to authenticated with check(public.is_admin() and created_by=auth.uid());
create policy posts_update on public.posts for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy posts_delete on public.posts for delete to authenticated using(public.is_admin());
create policy picks_insert on public.weekly_picks for insert to authenticated with check(public.is_admin() and created_by=auth.uid());
create policy picks_update on public.weekly_picks for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy picks_delete on public.weekly_picks for delete to authenticated using(public.is_admin());
create policy media_insert on public.media for insert to authenticated with check(public.is_admin() and created_by=auth.uid());
create policy media_update on public.media for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy media_delete on public.media for delete to authenticated using(public.is_admin());
commit;
